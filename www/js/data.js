const FA_DIGITS = '۰۱۲۳۴۵۶۷۸۹';
function fa(n){
  if(n === undefined || n === null) return '۰';
  if(typeof n === 'number'){ if(!isFinite(n)) return '۰'; n = (Math.round(n*10)/10); n = (n%1===0) ? String(Math.round(n)) : n.toFixed(1); }
  return String(n).replace(/\d/g, d => FA_DIGITS[+d]);
}

